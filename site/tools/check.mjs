// Static checks for the website. Zero dependencies (runs in the Pages workflow before upload).
// Usage: node site/tools/check.mjs   (exit 1 on any failure)
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { htmlPages, visibleFaq } from './sync-partials.mjs'

const SITE = fileURLToPath(new URL('..', import.meta.url))
const REPO = resolve(SITE, '..')
const BASE = 'https://hamzasohail123.github.io/sessionforge/'
// Every page except 404.html (the docs are generated by build-docs.mjs)
const PAGES = htmlPages().map((f) => relative(SITE, f).split(sep).join('/')).filter((r) => r !== '404.html').map((r) => r.replace(/index\.html$/, ''))
const BANNED = ['revolutionary', 'supercharge', 'seamless', 'leverage', 'robust', 'game-changer', 'game changer', 'cutting-edge', 'unlock', 'effortless', 'blazing']
const MAX_SITE = 10 * 1024 * 1024
const MAX_VIDEO = 4 * 1024 * 1024

const errors = []
const fail = (file, msg) => errors.push(`${file}: ${msg}`)
const relName = (f) => relative(SITE, f).split(sep).join('/')
const attr = (tag, name) => {
  const m = new RegExp(`\\s${name}="([^"]*)"`).exec(tag)
  return m ? m[1] : null
}
const tags = (html, name) => html.match(new RegExp(`<${name}\\b[^>]*>`, 'gi')) ?? []
const meta = (html, key, value) => {
  const t = tags(html, 'meta').find((m) => attr(m, key) === value)
  return t ? attr(t, 'content') : null
}
const decode = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&')
const visibleText = (html) =>
  decode(
    html
      .replace(/<script[\s\S]*?<\/script>/gi, ' ')
      .replace(/<style[\s\S]*?<\/style>/gi, ' ')
      .replace(/<head[\s\S]*?<\/head>/i, ' ')
      .replace(/<[^>]+>/g, ' ')
  )
const idsOf = (html) => new Set([...html.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]))
const pageDir = (file) => {
  const r = relName(file)
  return r.endsWith('index.html') ? r.slice(0, -'index.html'.length) : ''
}

const titles = new Map()
const descriptions = new Map()
const cache = new Map()
const read = (f) => {
  if (!cache.has(f)) cache.set(f, readFileSync(f, 'utf8'))
  return cache.get(f)
}

/** Resolve a relative URL from a page to a file in site/ (dir → index.html). */
function resolveRef(fromFile, ref, base) {
  const [pathPart, hash] = ref.split('#')
  const fromDir = base ? SITE : dirname(fromFile)
  let target = pathPart ? resolve(fromDir, decodeURIComponent(pathPart.split('?')[0])) : fromFile
  if (pathPart && (pathPart.endsWith('/') || pathPart === '.' || pathPart === './')) target = join(target, 'index.html')
  else if (existsSync(target) && statSync(target).isDirectory()) target = join(target, 'index.html')
  return { target, hash }
}

for (const file of htmlPages()) {
  const name = relName(file)
  const html = read(file)
  const is404 = name === '404.html'
  const head = /<head>([\s\S]*?)<\/head>/i.exec(html)?.[1] ?? ''
  const base = is404 ? attr(tags(head, 'base')[0] ?? '', 'href') : null
  if (is404 && base !== '/sessionforge/') fail(name, '404.html needs <base href="/sessionforge/">')

  if ((html.match(/<h1\b/g) ?? []).length !== 1) fail(name, 'needs exactly one <h1>')
  const title = /<title>([^<]*)<\/title>/.exec(head)?.[1]
  const desc = meta(head, 'name', 'description')
  if (!title) fail(name, 'missing <title>')
  else {
    if (decode(title).length > 60) fail(name, `title longer than 60 chars (${decode(title).length})`)
    if (titles.has(title)) fail(name, `title duplicates ${titles.get(title)}`)
    titles.set(title, name)
  }
  if (!desc) fail(name, 'missing meta description')
  else {
    if (!is404 && (desc.length < 120 || desc.length > 160)) fail(name, `description length ${desc.length} not in 120-160`)
    if (descriptions.has(desc)) fail(name, `description duplicates ${descriptions.get(desc)}`)
    descriptions.set(desc, name)
  }
  if (!/http-equiv="Content-Security-Policy"/.test(head)) fail(name, 'missing CSP meta')

  if (!is404) {
    const expected = BASE + pageDir(file)
    const canonical = attr(tags(head, 'link').find((l) => attr(l, 'rel') === 'canonical') ?? '', 'href')
    if (canonical !== expected) fail(name, `canonical ${canonical} != ${expected}`)
    for (const p of ['og:type', 'og:site_name', 'og:title', 'og:description', 'og:url', 'og:image', 'og:image:width', 'og:image:height', 'og:image:alt']) {
      if (!meta(head, 'property', p)) fail(name, `missing ${p}`)
    }
    if (meta(head, 'property', 'og:url') !== expected) fail(name, 'og:url != canonical')
    for (const p of ['twitter:card', 'twitter:title', 'twitter:description', 'twitter:image']) if (!meta(head, 'name', p)) fail(name, `missing ${p}`)
  }

  // Scripts: only same-origin files and JSON-LD data
  const ld = []
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const type = attr(m[0], 'type')
    const src = attr(m[0], 'src')
    if (type === 'application/ld+json') {
      try {
        ld.push(JSON.parse(m[2]))
      } catch (e) {
        fail(name, `JSON-LD does not parse: ${e.message}`)
      }
    } else if (!src) fail(name, 'inline <script> (CSP forbids it)')
    else if (/^(https?:)?\/\//.test(src)) fail(name, `off-site script ${src}`)
  }
  const ldTypes = ld.flatMap((d) => (d['@graph'] ? d['@graph'] : [d])).map((d) => d['@type'])
  if (name === 'index.html') {
    for (const t of ['SoftwareApplication', 'FAQPage']) if (!ldTypes.includes(t)) fail(name, `missing ${t} JSON-LD`)
    const faq = ld.find((d) => d['@type'] === 'FAQPage')
    const visible = visibleFaq(html)
    const data = (faq?.mainEntity ?? []).map((q) => ({ q: q.name, a: q.acceptedAnswer?.text }))
    if (visible.length < 5 || JSON.stringify(visible) !== JSON.stringify(data)) fail(name, 'FAQPage JSON-LD differs from the visible FAQ (run sync-partials.mjs)')
  } else if (!is404) {
    for (const t of ['BreadcrumbList', 'TechArticle']) if (!ldTypes.includes(t)) fail(name, `missing ${t} JSON-LD`)
  }

  if (/\sstyle="/.test(html)) fail(name, 'style= attribute (CSP forbids inline styles)')
  if (/<style\b/i.test(html)) fail(name, '<style> element (CSP forbids inline styles)')
  if (/target="_blank"/.test(html)) fail(name, 'target="_blank" (links open in the same tab)')
  for (const img of tags(html, 'img')) {
    for (const a of ['alt', 'width', 'height']) if (attr(img, a) === null) fail(name, `<img> without ${a}: ${img.slice(0, 80)}`)
  }
  for (const t of [...tags(html, 'link'), ...tags(html, 'img'), ...tags(html, 'source'), ...tags(html, 'video')]) {
    for (const a of ['href', 'src', 'poster']) {
      const v = attr(t, a)
      if (v && /^(https?:)?\/\//.test(v) && !(t.startsWith('<link') && ['canonical'].includes(attr(t, 'rel')))) fail(name, `off-site asset ${v}`)
    }
  }

  // Every relative reference resolves, including #anchors
  const refs = []
  for (const m of html.matchAll(/\s(href|src|poster)="([^"]*)"/g)) refs.push(m[2])
  for (const m of html.matchAll(/\ssrcset="([^"]*)"/g)) for (const part of m[1].split(',')) refs.push(part.trim().split(/\s+/)[0])
  const ids = idsOf(html)
  for (const ref of refs) {
    if (!ref) {
      fail(name, 'empty href/src')
      continue
    }
    if (/^(https?:|mailto:|data:)/.test(ref)) continue
    if (ref.startsWith('/') && !is404) fail(name, `root-absolute path ${ref} (breaks under /sessionforge/)`)
    if (ref.startsWith('/')) continue
    if (ref.startsWith('#')) {
      if (ref.length > 1 && !ids.has(ref.slice(1))) fail(name, `missing anchor ${ref}`)
      continue
    }
    const { target, hash } = resolveRef(file, ref, base)
    if (!target.startsWith(SITE) || !existsSync(target)) {
      fail(name, `broken link ${ref}`)
      continue
    }
    if (target.split(sep).includes('tools')) fail(name, `links into tools/ (not deployed): ${ref}`)
    if (hash && target.endsWith('.html') && !idsOf(read(target)).has(hash)) fail(name, `missing anchor ${ref}`)
  }

  const text = visibleText(html)
  if (text.includes('\u2014')) fail(name, 'em dash in visible text')
  for (const w of BANNED) if (new RegExp(`\\b${w}`, 'i').test(text)) fail(name, `banned word "${w}"`)
  if (/\b(export to playwright|storageState export)\b/i.test(text) && !/planned/i.test(text)) fail(name, 'mentions Playwright export without "planned"')
}

// Snippets must match the README byte for byte
const readmePath = join(REPO, 'README.md')
if (existsSync(readmePath)) {
  const readme = readFileSync(readmePath, 'utf8')
  const block = (after, lang) => {
    const i = readme.indexOf(after)
    if (i < 0) return null
    const m = new RegExp('( *)```' + lang + '\\n([\\s\\S]*?)\\n *```').exec(readme.slice(i))
    if (!m) return null
    return m[2]
      .split('\n')
      .map((l) => (l.startsWith(m[1]) ? l.slice(m[1].length) : l))
      .join('\n')
  }
  const expected = {
    export: block('Click **Copy export line**', 'sh'),
    cursor: block('**Cursor**: `.cursor/mcp.json`', 'json'),
    codex: block('**Codex** (CLI, VS Code extension and app share it)', 'toml'),
    claude: block('**Claude Code**: run once', 'sh')
  }
  for (const [k, v] of Object.entries(expected)) if (!v) errors.push(`README.md: could not find the ${k} snippet`)
  let found = 0
  for (const file of htmlPages()) {
    for (const m of read(file).matchAll(/<code id="[^"]+" data-snippet="(\w+)">([\s\S]*?)<\/code>/g)) {
      found++
      if (decode(m[2]) !== expected[m[1]]) fail(relName(file), `${m[1]} snippet differs from README.md`)
    }
  }
  if (found < 8) errors.push(`expected at least 8 data-snippet blocks, found ${found}`)
} else console.log('README.md not found; snippet comparison skipped')

// Discoverability files
const sitemap = existsSync(join(SITE, 'sitemap.xml')) ? readFileSync(join(SITE, 'sitemap.xml'), 'utf8') : ''
const locs = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]).sort()
if (JSON.stringify(locs) !== JSON.stringify(PAGES.map((p) => BASE + p).sort())) errors.push(`sitemap.xml must list exactly the ${PAGES.length} pages`)
for (const p of PAGES) if (!existsSync(join(SITE, p, 'index.html'))) errors.push(`missing page ${p || '(home)'}`)
for (const f of ['robots.txt', 'llms.txt', '.nojekyll', 'og.png', 'favicon.ico', 'favicon.svg', 'favicon-16.png', 'favicon-32.png', 'icon-192.png', 'icon-512.png', 'apple-touch-icon.png', 'site.webmanifest', '404.html']) {
  if (!existsSync(join(SITE, f))) errors.push(`missing ${f}`)
}
const robots = existsSync(join(SITE, 'robots.txt')) ? readFileSync(join(SITE, 'robots.txt'), 'utf8') : ''
if (!/User-agent: \*\nAllow: \//.test(robots) || /Disallow/.test(robots)) errors.push('robots.txt must allow everything')
if (readFileSync(join(SITE, 'llms.txt'), 'utf8').includes('\u2014')) errors.push('llms.txt: em dash')

// No third-party URLs in our JS and CSS (the vendored three.js is checked for fetches separately)
for (const f of ['assets/js/site.js', 'assets/js/theme.js', 'assets/js/hero.js', 'assets/js/docs.js', 'assets/js/docs-index.js', 'assets/css/site.css']) {
  const src = readFileSync(join(SITE, f), 'utf8')
  // docs-index.js holds page text (which mentions URLs such as 127.0.0.1); it is data, not requests
  if (!f.endsWith('docs-index.js') && /https?:\/\//.test(src)) errors.push(`${f}: contains an absolute URL`)
  if (/\bfetch\(|XMLHttpRequest|sendBeacon|document\.cookie/.test(src)) errors.push(`${f}: network or cookie API`)
}
if (!existsSync(join(SITE, 'assets/vendor/three/LICENSE'))) errors.push('three.js LICENSE missing')

// Size budget (what Pages deploys: site/ without tools/)
function du(dir) {
  let total = 0
  for (const n of readdirSync(dir)) {
    const p = join(dir, n)
    if (p === join(SITE, 'tools')) continue
    const s = statSync(p)
    total += s.isDirectory() ? du(p) : s.size
  }
  return total
}
const total = du(SITE)
if (total > MAX_SITE) errors.push(`site is ${(total / 1048576).toFixed(2)} MB (max 10 MB)`)
for (const v of ['demo.mp4', 'demo.webm']) {
  const p = join(SITE, 'assets/video', v)
  if (!existsSync(p)) errors.push(`missing ${v}`)
  else if (statSync(p).size > MAX_VIDEO) errors.push(`${v} is over 4 MB`)
}

if (errors.length) {
  console.error(errors.map((e) => `✗ ${e}`).join('\n'))
  console.error(`\n${errors.length} problem(s)`)
  process.exit(1)
}
console.log(`site check passed: ${htmlPages().length} pages, ${(total / 1048576).toFixed(2)} MB deployed`)
